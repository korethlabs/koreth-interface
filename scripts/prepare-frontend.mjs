#!/usr/bin/env node
// Generate typed contract addresses + ABIs for the interface from the local deployment:
//   src/generated/deployments.ts  <- addresses/chainId from koreth-v1-core/deployments/local.json
//   src/generated/abis.ts         <- ABIs (as const) from koreth-v1-core/out (ERC20 comes from viem)
//
// Usage (from the interface repo): node scripts/prepare-frontend.mjs
// Sibling multi-repo layout: contracts live in koreth-v1-core. Override with CORE_ROOT.
import {readFileSync, writeFileSync, mkdirSync} from "node:fs";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";
import {ABI_ARTIFACTS, DEPLOYMENT_KEYS, NUMERIC_KEYS} from "./core-artifacts.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const feRoot = join(here, "..");
const contractsRoot = process.env.CORE_ROOT || join(feRoot, "..", "koreth-v1-core");
const outDir = join(contractsRoot, "out");
const genDir = join(feRoot, "src", "generated");

const dep = JSON.parse(readFileSync(join(contractsRoot, "deployments", "local.json"), "utf8"));

mkdirSync(genDir, {recursive: true});

// --- deployments.ts ---
// Quoting follows NUMERIC_KEYS rather than the runtime type, so the emitted types are a
// property of this repo and not of however local.json happened to be serialized — a chainId
// that arrived as "1337" would otherwise silently become a string the whole app compares against.
//
// A key the app asks for and the deployment does not carry is a failure, not an omission: emitting
// the object without it leaves `deployments.someKey` typed and undefined, which reaches the chain as
// a call to no address rather than as a build that refused to finish. Same rule the subgraph's
// prepare-local.mjs applies to its own addresses.
const entries = DEPLOYMENT_KEYS
    .map((k) => {
        if (dep[k] === undefined) throw new Error(`local.json: missing '${k}'`);
        const numeric = NUMERIC_KEYS.has(k);
        if (numeric !== (typeof dep[k] === "number")) {
            throw new Error(`local.json: ${k} should be ${numeric ? "a number" : "a string"}, got ${typeof dep[k]}`);
        }
        return `  ${k}: ${numeric ? dep[k] : `"${dep[k]}"`},`;
    })
    .join("\n");
writeFileSync(
    join(genDir, "deployments.ts"),
    `// AUTO-GENERATED by scripts/prepare-frontend.mjs — do not edit.\nexport const deployments = {\n${entries}\n} as const;\n`,
);
console.log("gen -> src/generated/deployments.ts");

// --- abis.ts ---
let abiFile = "// AUTO-GENERATED by scripts/prepare-frontend.mjs — do not edit.\n";
for (const [name, artifact] of Object.entries(ABI_ARTIFACTS)) {
    const art = JSON.parse(readFileSync(join(outDir, artifact), "utf8"));
    if (!Array.isArray(art.abi)) throw new Error(`No .abi array in ${artifact}`);
    abiFile += `\nexport const ${name} = ${JSON.stringify(art.abi)} as const;\n`;
}
writeFileSync(join(genDir, "abis.ts"), abiFile);
console.log("gen -> src/generated/abis.ts");
